def render_tasks_page(tasks: list, by_id: dict) -> str:
    """The "I've been asked to…" index.

    Most people arrive with a request from someone else, not a browsing intent.
    This maps the ask, in the words it usually arrives in, to a starting order.
    """
    path = "tasks.md"
    parts = [BANNER.format(source="tasks.yml")]
    parts.append("# I've been asked to…\n")
    parts.append(
        "Most people land here because someone asked them for something. Find "
        "the request below and start where it points.\n"
    )
    parts.append(
        SNIPPET_ASSESS.format(assess=rel_link(path, "assess/index.md"))
    )
    for t in tasks:
        parts.append(f'## "{t["ask"]}"\n')
        parts.append(
            f"**Usually asked by:** {t['who']}  \n"
            f"**Rough effort:** {t['effort']}\n"
        )
        parts.append("**Start here, in this order:**\n")
        for n, tid in enumerate(t["start"], start=1):
            tpl = by_id.get(tid)
            if tpl is None:
                raise SystemExit(
                    f"ERROR: task {t['ask']!r} references unknown template '{tid}'"
                )
            parts.append(
                f"{n}. [{tpl['title']}]({rel_link(path, tpl['path'])})"
                f" — {' '.join(tpl['purpose'].split())[:110].rsplit(' ', 1)[0]}…"
            )
        parts.append("")
        parts.append(
            f'!!! tip "Before you start"\n'
            f"    {' '.join(t['note'].split())}\n"
        )
    parts.append(SNIPPETS_CACHE["not_legal_advice"])
    return "\n".join(parts)


def render_markdown_download(t: dict, by_id: dict, questions: list) -> str:
    """The template as standalone Markdown, for pasting into a wiki.

    Cross-references become plain template names rather than relative links,
    since those links would be broken once the file leaves the site.
    """
    def plain(text):
        return re.sub(
            r"\{\{([a-z0-9\-]+)\}\}",
            lambda m: by_id[m.group(1)]["title"] if m.group(1) in by_id else m.group(1),
            text or "",
        )

    out = [f"# {t['title']}\n"]
    out.append(f"**Purpose.** {plain(' '.join(t['purpose'].split()))}\n")
    out.append(f"**When to use it.** {plain(' '.join(t['when_to_use'].split()))}\n")
    out.append(f"**How to use it.** {plain(' '.join(t['how_to_use'].split()))}\n")
    out.append("---\n")

    if t.get("generate_body") == "checklist":
        items = sorted([q for q in questions if q.get("checklist")],
                       key=lambda q: q["checklist"])
        current = None
        for q in items:
            if q["category"] != current:
                current = q["category"]
                out.append(f"\n## {current}\n")
            out.append(f"- [ ] **{q['checklist']}.** {q['text']}")
            out.append(f"      *{' '.join(q['help'].split())}*")
            if q.get("evidence"):
                out.append(f"      **Evidence:** {' '.join(q['evidence'].split())}")
            out.append("")
        out.append("")
    else:
        # Admonitions are MkDocs-specific; flatten them to blockquotes so the
        # file renders sensibly in GitHub, Notion, Confluence, and plain editors.
        body = plain(t["body"].rstrip())
        lines, flat = body.split("\n"), []
        i = 0
        while i < len(lines):
            m = re.match(r'^!!!\s+\w+\s*"?([^"]*)"?\s*$', lines[i].strip())
            if m:
                flat.append(f"> **{m.group(1).strip() or 'Note'}**")
                i += 1
                while i < len(lines) and (not lines[i].strip()
                                          or lines[i].startswith("    ")):
                    if lines[i].strip():
                        flat.append("> " + lines[i].strip())
                    i += 1
                flat.append("")
                continue
            flat.append(lines[i])
            i += 1
        out.append("\n".join(flat) + "\n")

    out.append("---\n")
    out.append("## Adaptation notes\n")
    for note in t["adaptation"]:
        out.append(f"- **{note['context']}:** {plain(' '.join(note['note'].split()))}")
    out.append("")
    out.append("---\n")
    out.append(
        "*From the [Open Data & AI Governance Kit]"
        "(https://lsdeva.github.io/governance-kit/). Licensed "
        "[CC BY 4.0](https://creativecommons.org/licenses/by/4.0/) — free to use, "
        "adapt, and share with attribution.*\n"
    )
    out.append(
        "***Not legal advice.** Adapt to your jurisdiction, sector, and risk "
        "appetite, and have qualified counsel review anything material.*\n"
    )
    return "\n".join(out)


def render_section_index(section: dict, templates: list, by_id: dict) -> str:
    path = f"{section['id']}/index.md"
    parts = [BANNER.format(source="sections.yml + templates.yml")]
    parts.append(f"# {section['title']}\n")
    parts.append(section["blurb"].strip() + "\n")
    parts.append("| Template | Status | Purpose |")
    parts.append("|---|---|---|")
    for t in templates:
        purpose = " ".join(t["purpose"].split())
        if len(purpose) > 155:
            purpose = purpose[:152].rsplit(" ", 1)[0] + "…"
        parts.append(
            f"| [{t['title']}]({rel_link(path, t['path'])}) "
            f"| {status_pill(t['status'])} | {purpose} |"
        )
    parts.append("")
    parts.append(
        SNIPPET_ASSESS.format(assess=rel_link(path, "assess/index.md"))
    )
    return "\n".join(parts)


SNIPPET_ASSESS = ""  # filled from snippets.yml at runtime
