#!/usr/bin/env python3
"""Generate the site's Markdown pages and the assessment data from data/*.yml.

The data files under data/ are the single source of truth. This script renders:

  * one page per template            -> docs/<section>/<page>.md
  * one index page per section       -> docs/<section>/index.md
  * the EU AI Act readiness checklist -> generated from questions.yml
  * the assessment app's data        -> docs/assess/assessment-data.json
  * the navigation block             -> mkdocs.yml (between NAV markers)

Every generated file carries a "do not edit" header. CI re-runs this script and
fails if the working tree changed, so a hand-edit of a generated page is caught
loudly instead of being silently overwritten on the next build.

Usage:
    python tools/build_content.py            # write files
    python tools/build_content.py --check    # verify only; non-zero if stale
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from collections import Counter
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data"
DOCS = ROOT / "docs"

BANNER = (
    "<!-- GENERATED FILE — DO NOT EDIT.\n"
    "     Source: data/{source}\n"
    "     Regenerate with: python tools/build_content.py -->\n\n"
)

NAV_START = "# NAV:START (generated by tools/build_content.py - do not edit by hand)"
NAV_END = "# NAV:END"

STATUS_LABELS = {"ready": "Ready", "draft": "Draft", "stub": "Stub"}

# Template ids that also get an .xlsx. Populated from data/spreadsheets.yml at
# runtime so the download buttons cannot advertise a file that is not built.
SPREADSHEET_IDS = set()

# Order categories appear in the questionnaire and the report.
CATEGORY_ORDER = [
    "Inventory",
    "Risk",
    "Documentation",
    "Oversight",
    "Transparency",
    "Third-party",
    "Literacy",
]

# Readiness bands, shared by the report and the checklist page.
BANDS = [
    {"min": 90, "label": "Advanced", "blurb": "Controls are measured and independently assured. Focus on continuous improvement."},
    {"min": 70, "label": "Established", "blurb": "The core is in place and operating. Focus on evidencing that controls work."},
    {"min": 40, "label": "Developing", "blurb": "Foundations exist but coverage is uneven. Close the documentation and process gaps."},
    {"min": 0, "label": "Early", "blurb": "Significant exposure. Start with inventory, prohibited-practice screening, and accountability."},
]


def load(name: str):
    with open(DATA / name, encoding="utf-8") as fh:
        return yaml.safe_load(fh)


def rel_link(from_path: str, to_path: str) -> str:
    """Relative link from one docs page to another, MkDocs-style."""
    from_dir = Path(from_path).parent
    return Path(__import__("os").path.relpath(Path(to_path), from_dir)).as_posix()


def resolve_links(text: str, from_path: str, by_id: dict) -> str:
    """Replace {{template-id}} with a proper relative Markdown link.

    Keeping cross-references as ids means a page can be moved by changing its
    `path` in the data file without producing a single broken link.
    """
    if not text:
        return text

    def sub(match: re.Match) -> str:
        tid = match.group(1).strip()
        target = by_id.get(tid)
        if target is None:
            raise SystemExit(
                f"ERROR: unknown template id '{{{{{tid}}}}}' referenced from {from_path}"
            )
        return f"[{target['title']}]({rel_link(from_path, target['path'])})"

    return re.sub(r"\{\{([a-z0-9\-]+)\}\}", sub, text)


def status_pill(status: str) -> str:
    return f'<span class="pill {status}">{STATUS_LABELS[status]}</span>'


def build_checklist_body(questions: list, templates_by_id: dict, page_path: str) -> str:
    """Render the 25-point checklist FROM the question bank.

    This is why the published checklist and the assessment tool cannot drift:
    both read the same list.
    """
    items = sorted(
        [q for q in questions if q.get("checklist")], key=lambda q: q["checklist"]
    )
    groups: dict[str, list] = {}
    for q in items:
        groups.setdefault(q["category"], []).append(q)

    out = [
        "This checklist is generated from the same question bank as the "
        "[interactive assessment](" + rel_link(page_path, "assess/index.md") + "), "
        "so the two can never disagree.\n",
        "**Tick the boxes as you go** — your progress is saved in this browser "
        "and nothing is uploaded.\n",
        # docs/assess/checklist.js finds this element, enables the checkboxes,
        # and renders the live count and clear control into it.
        '<div id="gk-checklist" class="gk-cl"></div>\n',
    ]

    for category in CATEGORY_ORDER:
        if category not in groups:
            continue
        out.append(f"### {category}\n")
        for q in groups[category]:
            n = q["checklist"]
            out.append(f"- [ ] **{n}.** {q['text']}")
            out.append(f"    <br><small>{q['help'].strip()}</small>")
            if q.get("evidence"):
                out.append(
                    "    <br><small class=\"gk-ev\">**Evidence:** "
                    + " ".join(q["evidence"].split()) + "</small>"
                )
            tpl = [templates_by_id[t] for t in q.get("templates", []) if t in templates_by_id]
            if tpl:
                links = " · ".join(
                    f"[{t['title']}]({rel_link(page_path, t['path'])})" for t in tpl[:3]
                )
                out.append(f"    <br><small>**Fix with:** {links}</small>")
            out.append("")

    out.append("---\n")
    out.append("### Turn gaps into action\n")
    out.append(
        "Every unticked item maps to something in this kit. For a scored, "
        "role-specific version of this checklist — with a report you can present "
        "to a board or a regulator — take the "
        f"[interactive assessment]({rel_link(page_path, 'assess/index.md')}). "
        "Your answers stay in your browser.\n"
    )
    return "\n".join(out)


def render_template_page(t: dict, by_id: dict, snippets: dict, questions: list) -> str:
    path = t["path"]
    parts = [BANNER.format(source="templates.yml")]
    parts.append(f"# {t['title']}\n")

    # Status pill, plus review metadata where a page carries it. Time-sensitive
    # pages say when they were last checked, so a reader can judge staleness
    # rather than assume currency.
    meta = [status_pill(t["status"])]
    if t.get("version"):
        meta.append(f'<span class="gk-meta">v{t["version"]}</span>')
    if t.get("reviewed"):
        meta.append(
            f'<span class="gk-meta">Last reviewed <strong>{t["reviewed"]}</strong></span>'
        )
    parts.append(" &nbsp;·&nbsp; ".join(meta) + "\n")

    if t["status"] == "stub":
        parts.append(
            snippets["stub_invite"].format(contributing=rel_link(path, "contributing.md"))
        )
    elif t["status"] == "draft":
        parts.append(
            snippets["draft_note"].format(contributing=rel_link(path, "contributing.md"))
        )

    # Download buttons. build_downloads.py writes one .docx per template and a
    # .xlsx for anything in spreadsheets.yml; these links must match its output.
    dl = rel_link(path, "downloads/x").rsplit("/", 1)[0]
    buttons = [
        f'[:material-file-word: Word]({dl}/{t["id"]}.docx)'
        '{ .md-button .gk-dl download }'
    ]
    if t["id"] in SPREADSHEET_IDS:
        buttons.append(
            f'[:material-file-excel: Excel]({dl}/{t["id"]}.xlsx)'
            '{ .md-button .gk-dl download }'
        )
    buttons.append(
        f'[:material-language-markdown: Markdown]({dl}/{t["id"]}.md.txt)'
        f'{{ .md-button .gk-dl download="{t["id"]}.md" }}'
    )
    parts.append('<div class="gk-downloads" markdown>\n'
                 + "\n".join(buttons) + "\n</div>\n")

    ex = EXAMPLE_OF.get(t["id"])
    if ex:
        parts.append(
            f'!!! example "See this filled in"\n'
            f"    A [worked example]({rel_link(path, ex['path'])}) shows this\n"
            f"    template completed for a fictional mid-size company.\n"
        )

    parts.append(f"**Purpose.** {resolve_links(t['purpose'].strip(), path, by_id)}\n")
    parts.append(f"**When to use it.** {resolve_links(t['when_to_use'].strip(), path, by_id)}\n")
    parts.append(f"**How to use it.** {resolve_links(t['how_to_use'].strip(), path, by_id)}\n")

    # Which assessment questions this template answers — generated, so adding a
    # question automatically surfaces it on the pages that fix it.
    related_qs = [q for q in questions if t["id"] in q.get("templates", [])]
    if related_qs:
        qlist = ", ".join(f"**{q['id']}**" for q in related_qs[:8])
        parts.append(
            f"!!! tip \"Closes assessment gaps\"\n"
            f"    This template addresses {qlist} in the "
            f"[readiness assessment]({rel_link(path, 'assess/index.md')}).\n"
        )

    parts.append("---\n")
    parts.append("## The template\n")

    if t.get("generate_body") == "checklist":
        parts.append(build_checklist_body(questions, by_id, path))
    else:
        parts.append(resolve_links(t["body"].rstrip(), path, by_id) + "\n")

    parts.append("---\n")
    parts.append("## Adaptation notes\n")
    for note in t["adaptation"]:
        body = resolve_links(note["note"].strip(), path, by_id)
        parts.append(f"- **{note['context']}:** {body}")
    parts.append("")

    related = [by_id[r] for r in t.get("related", []) if r in by_id]
    if related:
        parts.append("## Related\n")
        for r in related:
            parts.append(
                f"- [{r['title']}]({rel_link(path, r['path'])}) "
                f"— {status_pill(r['status'])}"
            )
        parts.append("")

    parts.append(snippets["not_legal_advice"])
    return "\n".join(parts)


def render_example_page(ex: dict, company: dict, by_id: dict) -> str:
    """A worked example: the same template, filled in for the fictional company."""
    path = ex["path"]
    tpl = by_id[ex["of"]]
    parts = [BANNER.format(source="examples.yml")]
    parts.append(f"# {ex['title']}\n")
    parts.append(
        f'!!! info "A worked example, not a template"\n'
        f"    This shows {company['name']} — a fictional company — using the\n"
        f"    [{tpl['title']}]({rel_link(path, tpl['path'])}). To start your own,\n"
        f"    use the blank template. Details here are illustrative.\n"
    )
    parts.append(resolve_links(ex["intro"].strip(), path, by_id) + "\n")
    parts.append("---\n")
    parts.append(resolve_links(ex["body"].rstrip(), path, by_id) + "\n")
    parts.append("---\n")
    parts.append("## What to take from this\n")
    for t_ in ex["takeaways"]:
        parts.append(f"- {resolve_links(' '.join(t_.split()), path, by_id)}")
    parts.append("")
    parts.append(
        f"[Use the blank {tpl['title']}]({rel_link(path, tpl['path'])})"
        "{ .md-button .md-button--primary }\n"
    )
    parts.append(SNIPPETS_CACHE["not_legal_advice"])
    return "\n".join(parts)


